export type StyleConcept = (typeof styleConcepts)[number];
export type PreferenceVector = readonly [number, number, number];
export type CatalogProduct = {
  id: number;
  alt: string;
  extension: "jpg" | "png";
  category: "dress" | "jumpsuit";
  colours: string[];
  pattern: "plain" | "floral" | "stripe" | "abstract" | "small print";
  concepts: StyleConcept[];
  // 0–4: minimal→expressive, relaxed→structured, neutral→colourful.
  preferences: PreferenceVector;
};
function item(
  id: number,
  alt: string,
  extension: CatalogProduct["extension"],
  colours: string[],
  pattern: CatalogProduct["pattern"],
  concepts: StyleConcept[],
  preferences: PreferenceVector,
  category: CatalogProduct["category"] = "dress",
): CatalogProduct {
  return {
    id,
    alt,
    extension,
    colours,
    pattern,
    concepts,
    preferences,
    category,
  };
}
