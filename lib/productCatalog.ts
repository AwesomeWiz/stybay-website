/** Stable, local editorial ordering. Ties retain catalogue order. */
export function rankByPreferences(
  pool: number[],
  preference: PreferenceVector,
) {
  return pool
    .map((index, order) => ({
      index,
      order,
      distance: productCatalog[index].preferences.reduce(
        (sum, value, axis) => sum + (value - preference[axis]) ** 2,
        0,
      ),
    }))
    .sort((a, b) => a.distance - b.distance || a.order - b.order)
    .map(({ index }) => index);
}
